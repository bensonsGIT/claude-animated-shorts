# One timing table for picture, captions and sound, built from the narration (words.json + beats.json).
# Every word gets a key: normalised text, plus 2, 3... for repeats (e.g. "newton", "newton2").
# Outputs: <worktree>/shorts/src/videos/newton/timing.ts, ~/newton-short/timing.json
import json, math, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
TS_OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser(
    "~/claude-animated-shorts/.claude/worktrees/newton-short/shorts/src/videos/newton/timing.ts")
FPS = 30
words = json.load(open(os.path.join(HERE, "words.json")))
beats = json.load(open(os.path.join(HERE, "beats.json")))
norm = lambda s: re.sub(r"[^a-z0-9]", "", s.lower())
WORD, seen = {}, {}
for w in words:
    k = norm(w["w"]) or "x"
    if k[0].isdigit():
        k = "y" + k
    seen[k] = seen.get(k, 0) + 1
    WORD[k if seen[k] == 1 else f"{k}{seen[k]}"] = w["s"]
WORD["end"] = words[-1]["e"]
DUR = beats["duration"]
TOTAL = math.ceil(DUR * FPS)
# first word onset of every beat (s)
BEAT = [next(w["s"] for w in words if w["s"] >= b["s"] - 1e-3) for b in beats["beats"]]
with open(TS_OUT, "w") as f:
    f.write("// GENERATED by ~/newton-short/voice/make_timing.py from the narration's word timings - do not edit by hand.\n")
    f.write(f"// voice: {beats['voice']} ({DUR:.2f} s)\n")
    f.write(f"export const TOTAL = {TOTAL};\n")
    f.write("export const WORD = " + json.dumps({k: round(v, 3) for k, v in WORD.items()}) + ";\n")
    f.write("/** first word onset (s) of each narration beat */\n")
    f.write(f"export const BEAT = {json.dumps([round(b, 3) for b in BEAT])};\n")
    f.write("/** every spoken word with its own punctuation (captions) */\n")
    f.write("export const WORDS: { w: string; s: number; e: number }[] = " + json.dumps(words) + ";\n")
json.dump({"fps": FPS, "total": TOTAL, "duration": DUR, "word": WORD, "beat": BEAT}, open(os.path.join(ROOT, "timing.json"), "w"), indent=1)
print(f"TOTAL {TOTAL} f ({DUR:.2f} s)")
print(" ".join(WORD.keys()))
